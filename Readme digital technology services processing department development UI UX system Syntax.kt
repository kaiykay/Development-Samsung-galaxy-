Getting Started

Prerequisites

Android Studio Arctic Fox or later.

Kotlin version 1.7+ installed.

Java JDK 11 or above.


Setup Steps

1. Configure API keys in the local.properties file:

API_KEY=your_api_key


2. Customize the UI/UX themes in the res/values/themes.xml directory.


3. Launch the application with:

./gradlew assembleDebug




